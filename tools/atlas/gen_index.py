# カード数は各章頁 (<atlas_dir>/<章>/index.html) の card を数え、台帳の行数と一致することを確かめる。
# 表は数値の列を折り返さず右揃え (桁は tabular-nums)、折り返すのは題の列だけ。幅が足りなければ横スクロール (.wide)。
# 文言は辞書 T から引く (--lang ja で切り替え; 既定は en)。出力は入力だけで決まる (日時などを埋めない)。
# 使い方: python3 -I tools/atlas/gen_index.py <ledger_dir> <atlas_dir> <out.html> [--lang ja]
